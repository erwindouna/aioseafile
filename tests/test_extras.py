async def test_paginated(  # pylint: disable=too-many-arguments,too-many-positional-arguments
    aresponses: ResponsesMockServer,
    seafile_client: Seafile,
    snapshot: SnapshotAssertion,
    call: Call,
    path: str,
    key: str,
    fixture: str,
    query: dict[str, str],
) -> None:
    """Test list methods fetch every page: a full page of one item, then an empty page."""
    item = json.loads(_fixture(fixture))[key][0]
    requests: list[dict[str, str]] = []

    async def full_page(request: Request) -> object:
        requests.append(dict(request.query))
        return aresponses.Response(status=200, headers=JSON, text=json.dumps({key: [item], "total_count": 2}))

    async def empty_page(request: Request) -> object:
        requests.append(dict(request.query))
        return aresponses.Response(status=200, headers=JSON, text=json.dumps({key: [], "total_count": 2}))

    aresponses.add(HOST, path, "GET", full_page)
    aresponses.add(HOST, path, "GET", empty_page)
    assert await call(seafile_client) == snapshot
    assert requests == snapshot(name="requests")
    assert all(request.items() >= query.items() for request in requests)
