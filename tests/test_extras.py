def _query(params: dict[str, Any]) -> list[tuple[str, str]]:
    """Flatten expected query parameters, with lists as repeated keys."""
    items = [(key, str(item)) for key, value in params.items() for item in (value if isinstance(value, list) else [value])]
    return sorted(items)


async def _capture(request: Request) -> dict[str, Any]:
    """Return the query, form body and JSON body of a request."""
    is_json = request.content_type == "application/json"
    return {
        "query": sorted(request.query.items()),
        "form": {} if is_json else dict(await request.post()),
        "json": await request.json() if is_json else None,
    }


